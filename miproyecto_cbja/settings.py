# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

DB_URL = config('DB_URL', default=config('DATABASE_URL', default='')).strip()
DB_HOST = config('DB_HOST', default='').strip()
DB_URL_PARSED = urlparse(DB_URL) if DB_URL and '://' in DB_URL else (urlparse(DB_HOST) if '://' in DB_HOST else None)

if DB_URL_PARSED and DB_URL_PARSED.scheme:
    DB_HOST_VALUE = DB_URL_PARSED.hostname or DB_HOST
    DB_NAME_VALUE = DB_URL_PARSED.path.lstrip('/') or config('DB_NAME', default='')
    DB_USER_VALUE = unquote(DB_URL_PARSED.username or config('DB_USER', default=''))
    DB_PASSWORD_VALUE = unquote(DB_URL_PARSED.password or config('DB_PASSWORD', default=''))
    DB_PORT_VALUE = str(DB_URL_PARSED.port or config('DB_PORT', default='3306'))
elif DB_HOST:
    DB_HOST_VALUE = DB_HOST
    DB_NAME_VALUE = config('DB_NAME', default='')
    DB_USER_VALUE = config('DB_USER', default='')
    DB_PASSWORD_VALUE = config('DB_PASSWORD', default='')
    DB_PORT_VALUE = config('DB_PORT', default='3306')
else:
    DB_HOST_VALUE = ''
    DB_NAME_VALUE = config('DB_NAME', default='')
    DB_USER_VALUE = config('DB_USER', default='')
    DB_PASSWORD_VALUE = config('DB_PASSWORD', default='')
    DB_PORT_VALUE = config('DB_PORT', default='3306')

if DB_HOST_VALUE:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': DB_NAME_VALUE,
            'USER': DB_USER_VALUE,
            'PASSWORD': DB_PASSWORD_VALUE,
            'HOST': DB_HOST_VALUE,
            'PORT': DB_PORT_VALUE,
            'OPTIONS': {'ssl': {'ssl-mode': 'REQUIRED'}},
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }

